"""Generates platform icons from the SVG sources in icons/.

    python tool/generate_icons.py

Android: adaptive + themed (monochrome) launcher icon and the notification icon as vector
drawables, plus PNG mipmaps for Android 7 (API 24/25) which has no adaptive icons.
Web: favicon and PWA icons. App: assets/app_icon.png.
PNGs are rendered with headless Microsoft Edge (set EDGE to override the path).
"""

import os
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / 'icons'
RES = ROOT / 'android/app/src/main/res'
EDGE = os.environ.get('EDGE', r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe')


def read_svg(name):
    text = (ICONS / name).read_text(encoding='utf-8')
    view = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    path = re.search(r'<path ([^>]*)/>', text).group(1)
    return {
        'text': text,
        'size': view[2],
        'd': re.search(r'\bd="([^"]+)"', path).group(1),
        'fill': re.search(r'\bfill="([^"]+)"', path).group(1),
        'opacity': float((re.search(r'fill-opacity="([^"]+)"', path) or re.search(r'()', '')).group(1) or 1),
        'bg': (re.search(r'<(?:rect|circle)[^>]*fill="([^"]+)"', text) or re.search(r'()', '')).group(1) or None,
    }


def color(c, opacity=1.0):
    c = {'white': '#FFFFFF', 'black': '#000000'}.get(c, c).lstrip('#')
    return f'#{round(opacity * 255):02X}{c.upper()}'


def vector(path_d, viewport, fill, size_dp, scale=1.0, offset=0.0):
    group_open = (f'    <group android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}" '
                  f'android:translateX="{offset:.4f}" android:translateY="{offset:.4f}">\n')
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/generate_icons.py from icons/*.svg. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport:g}" android:viewportHeight="{viewport:g}">\n'
        f'{group_open}'
        f'        <path android:fillColor="{fill}" android:pathData="{path_d}"/>\n'
        '    </group>\n'
        '</vector>\n'
    )


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8', newline='\n')
    print('wrote', path.relative_to(ROOT))


def render_png(svg_text, out, px, maskable_bg=None, inner=1.0):
    """Renders an SVG to a px*px PNG; optional full-bleed background with the art scaled to `inner`."""
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        svg_file = Path(tmp) / 'icon.svg'
        svg_file.write_text(svg_text, encoding='utf-8')
        art = round(px * inner)
        html = Path(tmp) / 'page.html'
        html.write_text(
            '<html><body style="margin:0;background:transparent">'
            f'<div style="width:{px}px;height:{px}px;display:flex;align-items:center;justify-content:center;'
            f'background:{maskable_bg or "transparent"}">'
            f'<img src="icon.svg" style="width:{art}px;height:{art}px"></div></body></html>',
            encoding='utf-8')
        shot = Path(tmp) / 'shot.png'
        subprocess.run([
            EDGE, '--headless', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
            '--default-background-color=00000000', f'--window-size={px},{px}',
            f'--screenshot={shot}', html.as_uri(),
        ], check=True, capture_output=True)
        out.write_bytes(shot.read_bytes())
    print('wrote', out.relative_to(ROOT), f'{px}px')


def main():
    app_fg = read_svg('app-icon-no-bg.svg')
    app_full = read_svg('app-icon-with-bg.svg')
    notif = read_svg('notification-icon-no-bg.svg')

    # Adaptive icon: 108dp canvas. The wide wordmark is mapped onto the central 66dp (21dp inset)
    # so it stays inside the safe zone of every mask shape (circle, squircle, ...).
    scale = 66 / app_fg['size']
    write(RES / 'drawable/ic_launcher_foreground.xml',
          vector(app_fg['d'], 108, color(app_fg['fill'], app_fg['opacity']), 108, scale, 21))
    write(RES / 'drawable/ic_launcher_monochrome.xml',
          vector(app_fg['d'], 108, '#FFFFFFFF', 108, scale, 21))
    write(RES / 'values/ic_launcher_background.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_icons.py. -->\n<resources>\n'
          f'    <color name="ic_launcher_background">{app_full["bg"]}</color>\n</resources>\n')
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_icons.py. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        '</adaptive-icon>\n')
    write(RES / 'mipmap-anydpi-v26/ic_launcher.xml', adaptive)

    # Notification small icon: white silhouette, 24dp.
    write(RES / 'drawable/ic_stat_notification.xml',
          vector(notif['d'], notif['size'], '#FFFFFFFF', 24))
    write(RES / 'values/notification_colors.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_icons.py. -->\n<resources>\n'
          f'    <color name="notification_accent">{read_svg("notification-icon-with-bg.svg")["bg"]}</color>\n</resources>\n')

    # Legacy launcher PNGs (API 24/25).
    for density, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        render_png(app_full['text'], RES / f'mipmap-{density}/ic_launcher.png', px)

    # Web.
    web = ROOT / 'web'
    render_png(app_full['text'], web / 'favicon.png', 32)
    render_png(app_full['text'], web / 'icons/Icon-192.png', 192)
    render_png(app_full['text'], web / 'icons/Icon-512.png', 512)
    # Maskable: full-bleed background, artwork inside the 80% safe zone.
    render_png(app_fg['text'], web / 'icons/Icon-maskable-192.png', 192, app_full['bg'], 0.8)
    render_png(app_fg['text'], web / 'icons/Icon-maskable-512.png', 512, app_full['bg'], 0.8)

    # In-app asset.
    render_png(app_full['text'], ROOT / 'assets/app_icon.png', 512)


if __name__ == '__main__':
    main()
